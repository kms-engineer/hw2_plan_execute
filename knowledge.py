class KnowledgeQuery(BaseModel):
    """Параметри пошуку правил проживання."""

    query: str = Field(min_length=MIN_QUERY_LEN,
                       description="Питання українською, напр. «чи можна з собакою і скільки це коштує»")
    hotel_id: str | None = Field(default=None, description="ID готелю (напр. LVI-002) — для правил конкретного "
                                                           "готелю; без нього — лише загальні правила мережі")
    topics: list[str] | None = Field(default=None, max_length=MAX_RESULTS,
                                     description=f"Теми питання (1–{MAX_RESULTS}): {', '.join(TOPICS)}. Повертаються "
                                                 "правила всіх названих тем — точніше, ніж пошук лише за текстом")

    @field_validator("hotel_id")
    @classmethod
    def known_hotel(cls, v: str | None) -> str | None:
        return None if v is None else check_hotel_id(v)

    @field_validator("topics")
    @classmethod
    def known_topics(cls, v: list[str] | None) -> list[str] | None:
        if not v:
            return None
        topics = list(dict.fromkeys(t.strip().lower() for t in v))
        if unknown := [t for t in topics if t not in TOPICS]:
            raise ValueError(f"Невідомі теми: {', '.join(unknown)}. Доступні: {', '.join(TOPICS)}")
        return topics


def label(meta: Metadata) -> str:
    """Підпис документа у виході: чиє це правило і з якої теми."""
    owner = "Правила мережі" if meta["hotel_id"] == NETWORK else f"Правила готелю {meta['title']}"
    return f"{owner} · {meta['topic']}"


Hit = tuple[float, str, Metadata]  # (релевантність 0–1, текст, метадані)


def rank(query: str, hotel_id: str | None = None, topics: list[str] | None = None) -> list[Hit]:
    """Фільтр за метаданими + ранжування + перекриття за темою. Без порогу: його застосовує select()."""
    where: Where = {"hotel_id": {"$in": [hotel_id, NETWORK]}} if hotel_id else {"hotel_id": NETWORK}
    if topics:
        by_topics: Where = {"topic": {"$in": [*topics]}}
        where = {"$and": [where, by_topics]}
    # Точна косинусна схожість для ВСІХ документів, що пройшли фільтр, а не query() з HNSW: наближений обхід графа
    # з вузьким фільтром (2 документи з 46) інколи не доходить до одного з них — і правило готелю губилося б.
    # ponytail: після фільтра — правила одного готелю + загальні (десятки документів навіть для тисяч готелів);
    # якщо тем на готель стануть сотні — звужувати за topic або брати query() з великим ef_search
    found = get_collection().get(where=where, include=["documents", "metadatas", "embeddings"])
    docs, metas, vectors = found["documents"], found["metadatas"], found["embeddings"]
    if not found["ids"]:
        return []
    assert docs is not None and metas is not None and vectors is not None  # include вище; у типах Chroma — Optional
    matrix = np.asarray(vectors, dtype=float)
    scores = matrix @ embed_query(query) / np.linalg.norm(matrix, axis=1)

    by_topic: dict[str, list[Hit]] = {}
    for doc, meta, score in zip(docs, metas, scores):
        by_topic.setdefault(str(meta["topic"]), []).append((max(0.0, float(score)), doc, meta))
    hits = []
    for group in by_topic.values():
        # Правило готелю замінює загальне правило теми й бере кращу оцінку групи: короткий текст готелю може бути
        # далі від запиту, ніж загальний документ на ту саму тему, але відповідає саме він
        doc, meta = next(((d, m) for _, d, m in group if m["hotel_id"] != NETWORK), group[0][1:])
        hits.append((max(score for score, _, _ in group), doc, meta))
    return sorted(hits, key=lambda h: -h[0])


def select(hits: list[Hit], min_relevance: float = MIN_RELEVANCE, margin: float = RELEVANCE_MARGIN) -> list[Hit]:
    """Динамічна кількість для пошуку без topics: усе ≥ min_relevance і не гірше за найкращий більше ніж на margin."""
    if not hits or hits[0][0] < min_relevance:
        return []
    return [h for h in hits if h[0] >= max(min_relevance, hits[0][0] - margin)][:MAX_RESULTS]


@tool(args_schema=KnowledgeQuery)
@doc_vars(max_results=MAX_RESULTS, min_len=MIN_QUERY_LEN,
          topics="; ".join(f"{t} ({hint})" for t, hint in TOPICS.items()))
def search_knowledge(query: str, hotel_id: str | None = None, topics: list[str] | None = None) -> str:
    """Шукає правила проживання: загальні правила мережі, а з hotel_id — і правила конкретного готелю.

    Теми правил: {topics}.

    Коли використовувати:
    - питання про правила без конкретного готелю («о котрій заселення», «які документи») — без hotel_id:
      відповідають стандартні правила мережі, готель НЕ уточнюй;
    - правила конкретного готелю — з hotel_id: правила цього готелю + загальні, правил інших готелів немає.
      Теми, де в готелю свої правила, перелічує get_hotel_details («Особливі правила готелю»);
    - якщо зрозуміло, яких тем стосується питання, — передай topics (напр. ["заселення", "документи"]): повернуться
      правила саме цих тем. Без topics пошук іде лише за текстом і на коротких питаннях може промахнутися.

    Коли НЕ використовувати:
    - факти про готель (чи дозволені тварини, чи є сніданок і його ціна, тариф скасування) → get_hotel_details;
    - пошук готелів, наявність, ціни → search_hotels; розрахунок → calculate_total_price; бронювання → book_hotel.

    Що повертає:
    - змінну кількість документів (1–{max_results}): з topics — по документу на кожну тему, для якої є правила
      (про теми без правил — окремий рядок); без topics — усе, що близьке за релевантністю до найкращого
      результату (зазвичай 1–2 документи однієї теми);
    - кожен документ з підписом «Правила мережі · тема» або «Правила готелю ID Назва · тема» і релевантністю 0–1;
    - правило готелю на тему замінює загальне правило цієї теми, тож суперечностей у виході немає;
    - якщо релевантних правил немає — так і сказано: не вигадуй відповідь.

    Помилки:
    - запит коротший за {min_len} симв. — retryable: переформулюй повніше;
    - невідомий hotel_id — retryable: візьми ID з результатів search_hotels;
    - невідома тема — retryable: обери з переліку вище або не передавай topics.
    """
    hits = rank(query, hotel_id, topics)
    if not hits:
        return f"Правил на теми {', '.join(topics)} не знайдено." if topics else "Релевантних правил не знайдено."
    if not topics:  # теми задано явно — повертаємо їхні правила без порогу
        if not (selected := select(hits)):
            return f"Релевантних правил не знайдено. Найближче: «{label(hits[0][2])}», релевантність {hits[0][0]:.2f}."
        hits = selected
    found = "\n---\n".join(f"[{label(meta)}] (релевантність {score:.2f}) {doc}"
                            for score, doc, meta in hits[:MAX_RESULTS])
    missing = [t for t in topics or [] if t not in {str(meta["topic"]) for _, _, meta in hits}]
    return found + (f"\n---\nПравил на теми {', '.join(missing)} немає ні в мережі, ні в цього готелю." if missing
                    else "")

